-- 1. Buat Tabel Promo
CREATE TABLE IF NOT EXISTS public.promo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kode VARCHAR(50) NOT NULL UNIQUE,
    deskripsi TEXT NOT NULL,
    diskon INT NOT NULL DEFAULT 0,
    status BOOLEAN DEFAULT true,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Atur RLS Publik
ALTER TABLE public.promo ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Allow Public Read Promo" ON public.promo FOR SELECT USING (true);
CREATE POLICY "Allow Public Insert Promo" ON public.promo FOR INSERT WITH CHECK (true);

